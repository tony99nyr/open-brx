"""The gun-reply cases (app/test/fixtures/gun-replies.json) cover what fake.py FakeTagger answers (A9).

The file is generated by app/test/fixtures/gen_gun_replies.py; app/test/fakegun-cases.test.mjs holds the e2e rig's gun
(app/src/fakegun.js) to it. Freshness of the file is test_generated_fresh.py's job."""
from __future__ import annotations

import importlib.util
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
_spec = importlib.util.spec_from_file_location("gen_gun_replies", ROOT / "app" / "test" / "fixtures" / "gen_gun_replies.py")
assert _spec and _spec.loader
GEN = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(GEN)


def test_the_cases_cover_the_head_the_spawn_and_the_probe():
    doc = GEN.document()
    replies = [f for c in doc["cases"] for s in c["steps"] for f in s["replies"]]
    for prefix in ("$ALCD,", "$LCD,", "$HP,", "$QUERY,"):
        assert any(f.startswith(prefix) for f in replies), prefix
    assert len({c["name"] for c in doc["cases"]}) == len(doc["cases"])
