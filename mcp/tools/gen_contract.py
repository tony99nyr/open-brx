#!/usr/bin/env python3
"""Generate the two client copies of the node<->MC wire contract from its one Python source.

    python3 mcp/tools/gen_contract.py            # rewrite both files
    python3 mcp/tools/gen_contract.py --check    # exit 1 if either is stale (what the test does)

Source of truth: `mcp/brx_mcp/mc/types.py` (constants, Literal aliases, TypedDicts, the kind
vocabularies) and `mcp/brx_mcp/mc/envelope.py` (`REQUIRED`/`EVENT_REQUIRED`/`ACCEPT_MIN`, plus its
own module-level UPPER_CASE constants -- the two size caps and the `t` sanity bounds). `docs/spec/
contracts.md` stays the human spec of record and generates nothing; this script generates the two
machine copies the UI and the phone app used to hand-keep:

  webapp/mc/src/api/contract.gen.ts   MC console (Vite/TS) -- constants, `type` aliases, every
                                      TypedDict as an `interface`, kind vocabularies as
                                      `[...] as const` arrays + their `typeof ...[number]` type,
                                      and the REQUIRED/EVENT_REQUIRED/ACCEPT_MIN tables.
  app/src/transport/contract.gen.js  phone app (esbuild) + node tests/tools -- the same constants
                                      and tables, kind vocabularies as `Set`s (matched to the exact
                                      literal form `test_contract_kinds.py`'s `_js_set()` regex and
                                      `test_mc_envelope_kinds.py` expect, so those tests can be
                                      pointed at this file later without touching their parsers).

Whole-file generation, not marker splicing: nothing hand-written lives in either output. Stdlib
only -- no dependency on the MC package having any of its own dependencies installed (it has none;
this script imports `brx_mcp.mc.types` / `.envelope` directly, which are pure).

2026-09-12 (contract-DRY phase 1, per docs scratch/contract-dry-spec.md). Modeled on
`gen_ui_catalog.py` (same `render()` / `main()` shape) and `test_ui_catalog_generated.py` (same
in-memory-render-vs-disk test pattern).
"""
