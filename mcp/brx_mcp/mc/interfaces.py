"""Cross-lane Protocols (docs/spec net.md §6, modes.md §7, armory.md §5). Lanes implement or
consume these; never import another lane's module internals."""
from __future__ import annotations

import random
from typing import TYPE_CHECKING, Any, Callable, Protocol

from ..hitaudio import Plan

from .types import (ArmoryRecord, Envelope, Event, FrameBundle, GameConfig, Player, RosterEntry,
                    PerkEffectsResolved, ScanRow, Team, Weapon, PerkView, VoiceOption)

if TYPE_CHECKING:
    from .compile import WeaponCatalog


class Hello(dict):
    """hello body: node_id, node_type, app_ver, gun?{name, tail, fw?}, seq_next"""


class WelcomeNode(dict):
    """welcome.node: player, team, roster, config, frames, start?, match_id?, score?"""


class NetServer(Protocol):
    async def start(self, host: str = "0.0.0.0", port: int = 8765, ws_path: str = "/ws",
                    *, advertise_host: str | None = None) -> None: ...   # real server is async; FakeNet's is sync
    @property
    def port(self) -> int: ...
    @property
    def nodes(self) -> dict[str, Any]: ...
    def join_info(self) -> dict: ...                       # {url, session_id, qr}
    def hydrate(self, cb: Callable[[Hello], WelcomeNode | None]) -> None: ...
    def retain(self, cb: Callable[[str], bool]) -> None: ...
    def resolve_gun(self, cb: Callable[[str, str], str | None]) -> None: ...
    def set_join(self, *, secret: str | None = None, pub: str | None = None,
                 armed: bool | Callable[[], bool] | None = None) -> None: ...
    def on_node(self, cb: Callable[[dict], None]) -> None: ...
    def on_event(self, cb: Callable[[str, Event, int], None]) -> None: ...        # (node_id, ev, t_recv) — single facts
    def on_batch(self, cb: Callable[[str, list, int], None]) -> None: ...          # (node_id, events, t_recv) — a flushed event_batch (A5.7)
    def on_clock(self, cb: Callable[[str, int, int, str], None]) -> None: ...
    def on_status(self, cb: Callable[[str, dict, int], None]) -> None: ...
    def on_node_message(self, cb: Callable[[str, str, dict, int], None]) -> None: ...  # (node_id, kind, body, t_recv)
    def on_stale(self, cb: Callable[[str, int], None]) -> None: ...
    def on_return(self, cb: Callable[[str], None]) -> None: ...
    def on_disconnect(self, cb: Callable[[str], None]) -> None: ...
    def push(self, node_id: str, kind: str, body: dict) -> bool: ...
    def broadcast(self, kind: str, body: dict) -> int: ...
    def evict(self, node_id: str) -> bool: ...              # operator kick: close 4000, forget gun/player, rotate key (optional on fakes)


class CatalogView(Protocol):
    """The weapon catalogue as Session reads it (candidate 9): the real WeaponCatalog and the fake's both satisfy it."""
    def spawn_ammo(self, weapon_id: str, mods: dict | None = None) -> tuple[int, int]: ...
    def row(self, weapon_id: str) -> dict | None: ...
    def app_requirements(self) -> list[dict]: ...


class Compiler(Protocol):
    catalog: CatalogView
    bench_volume: int | None
    def compile(self, config: GameConfig, player: Player, teams: list[Team],
                roll: random.Random | None = None, plan: object | None = None) -> FrameBundle: ...
    def tutorial_frames(self, weapon: Weapon, environment: str, silent: bool = False) -> list[str]: ...
    def cues(self, voice: str, slots: dict | None = None, night: bool = False) -> dict[str, str]: ...
    def validate(self, config: GameConfig, roster: list[Player], opts: dict | None = None) -> dict: ...
    def weapon_catalog(self) -> list[Weapon]: ...
    def perk_catalog(self) -> list[PerkView]: ...
    def perk_effects(self, player: Player | None) -> dict: ...
    def perk_effects_resolved(self, config: GameConfig, player: Player | None) -> PerkEffectsResolved | None: ...
    def voice_options(self) -> list[VoiceOption]: ...
    def voice_preview(self, voice: str, slots: dict | None = None) -> str | None: ...
    def hit_plan(self, roster: list[Player], rekey: bool = False) -> Plan | None: ...   # None: no pinned plan (the fake)
    def plan_gaps(self, plan: Plan | None, player: Player) -> list[str]: ...


class Armory(Protocol):
    last_read_ok: bool
    corrupt: dict | None
    def list(self) -> list[ArmoryRecord]: ...
    async def scan(self, duration_s: int = 6) -> list[ScanRow]: ...
    def bind_player(self, gun_id: str, player_id: str) -> None: ...
    def dismiss_corrupt(self) -> bool: ...
