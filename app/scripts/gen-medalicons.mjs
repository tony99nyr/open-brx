#!/usr/bin/env node
// Copies the recap medal icons (app/src/hud/medalicons.js, the one source) into Mission Control as
// webapp/mc/src/api/medalicons.gen.ts, the way mcp/tools/gen_contract.py hands MC the contract. MC imports nothing
// from app/, so a generated copy is the simplest thing both builds and CI agree on.
// webapp/mc/test/medalicons-gen.test.ts fails when the copy is stale: run `node app/scripts/gen-medalicons.mjs`.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const SRC = path.join(ROOT, 'app', 'src', 'hud', 'medalicons.js');
const OUT = path.join(ROOT, 'webapp', 'mc', 'src', 'api', 'medalicons.gen.ts');
// The line the staleness test splits on: everything after it is the source, byte for byte.
const MARK = '// ---- app/src/hud/medalicons.js, verbatim ----\n';
const HEAD = '// GENERATED by app/scripts/gen-medalicons.mjs from app/src/hud/medalicons.js -- do not edit; run node app/scripts/gen-medalicons.mjs\n'
  + '// @ts-nocheck -- the source is plain JS; MC uses medalIcon(key, { size, label }) and medalChip(text, rows), which return strings\n';
writeFileSync(OUT, HEAD + MARK + readFileSync(SRC, 'utf8'));
console.log('wrote', path.relative(ROOT, OUT));
